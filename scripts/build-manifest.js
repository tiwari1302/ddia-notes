#!/usr/bin/env node
// Generates core/manifest.js: a small index of every deep dive (section ids/titles, embedded
// visualizations, quiz counts, reading time) so the app can draw the sidebar, dashboard,
// progress and Visualization lab without downloading the deep-dive files, which are
// lazy-loaded per chapter.
//
//   node scripts/build-manifest.js          # (re)write core/manifest.js
//   node scripts/build-manifest.js --check  # exit 1 if core/manifest.js is out of date
//
// Run it after editing any chapters/chN.deep*.js file (validate.js reports when it's stale).
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "core", "manifest.js");

function stripTags(s) {
  return String(s || "")
    .replace(/<\/?(b|strong|em|i|code|span|a|sup|sub|kbd|mark|small|u)\b[^>]*>/gi, "")
    .replace(/<[^>]+>/g, " ").replace(/&[a-z#0-9]+;/gi, " ").replace(/\s+/g, " ").trim();
}
function blockText(b) {
  switch (b.type) {
    case "realworld": return (b.items || []).map(i => `${i.org || ""} ${i.title || ""} ${i.html || ""}`).join(" ");
    case "tradeoffs": return (b.pros || []).concat(b.cons || []).join(" ");
    case "steps": case "list": case "keypoints": return (b.items || []).join(" ");
    case "timeline": return (b.items || []).map(i => `${i.year} ${i.html}`).join(" ");
    case "table": return (b.rows || []).map(r => r.join(" ")).join(" ");
    case "compare": return (b.items || []).map(i => `${i.title} ${i.html}`).join(" ");
    case "quiz": return `${b.q} ${(b.options || []).join(" ")} ${b.explain || ""}`;
    case "viz": return `${b.title || ""} ${b.caption || ""}`;
    case "code": case "diagram": return "";
    default: return `${b.title || ""} ${b.html || ""}`;
  }
}

function build() {
  const sb = { window: {}, console };
  sb.window.window = sb.window;
  vm.createContext(sb);
  const run = f => vm.runInContext(fs.readFileSync(path.join(ROOT, f), "utf8"), sb, { filename: f });
  run("core/registry.js");
  sb.DDIA = sb.window.DDIA;
  const files = fs.readdirSync(path.join(ROOT, "chapters"))
    .filter(f => /^ch\d+(\.deep2?)?\.js$/.test(f))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  files.forEach(f => run("chapters/" + f));
  const manifest = {};
  for (const ch of sb.window.DDIA.chapters) {
    const secs = (ch.deepDive && ch.deepDive.sections) || [];
    let words = stripTags(ch.deepDive && ch.deepDive.hook).split(" ").length;
    const entry = { sections: [], viz: [], quizzes: 0, words: 0, minutes: 0 };
    secs.forEach(s => {
      entry.sections.push({ id: s.id, title: s.title });
      (s.blocks || []).forEach(b => {
        words += stripTags(blockText(b)).split(" ").filter(Boolean).length;
        if (b.type === "viz") entry.viz.push({ id: b.id, title: b.title, caption: b.caption || "", section: s.id });
        if (b.type === "quiz") entry.quizzes++;
      });
    });
    entry.words = words;
    entry.minutes = Math.max(1, Math.round(words / 220));
    manifest[ch.id] = entry;
  }
  return "// GENERATED by scripts/build-manifest.js from chapters/*.deep*.js. Do not edit by hand.\n" +
    "// Lets the app show sections, progress and the Visualization lab before deep dives load.\n" +
    "window.DDIA_MANIFEST = " + JSON.stringify(manifest) + ";\n";
}

if (require.main === module) {
  const next = build();
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (cur !== next) { console.log("core/manifest.js is out of date: run node scripts/build-manifest.js"); process.exit(1); }
    console.log("core/manifest.js is up to date");
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`wrote core/manifest.js (${next.length} bytes)`);
  }
}
module.exports = { build, OUT };
